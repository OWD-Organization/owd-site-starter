export function isProductionBuild() {
  return process.env.VERCEL_ENV === 'production';
}

export function severityFor(rule, production) {
  return production && PRODUCTION_CRITICAL_RULES.has(rule) ? 'critical' : 'warn';
}

export function withFix(rule, msg) {
  const fix = FIX[rule];
  if (!fix || msg.includes('Fix:')) return msg;
  return `${msg} Fix: ${fix}`;
}

/** Why a host is not allowed on a canonical or sitemap URL, or null. */
export function badDomain(host, siteHost) {
  if (!host) return 'missing';
  if (host === 'vercel.app' || host.endsWith('.vercel.app')) return 'vercel.app';
  if (siteHost && host !== siteHost) return 'other';
  return null;
}

export function placeholderReasons(html) {
  const reasons = [];
  if (/\bTODO\b/.test(html)) reasons.push('the word TODO');
  if (/lorem ipsum/i.test(html)) reasons.push('lorem ipsum');
  if (/(?<![a-z0-9-])example\.com\b/i.test(html)) reasons.push('example.com');
  if (/href\s*=\s*(['"])[^'"]*#TODO\b/i.test(html)) reasons.push('a #TODO link');
  if (/\b555[-.\s)]*\d{3}[-.\s]*\d{4}\b/.test(html) || /tel:\s*\+?1?[-.\s(]*555/i.test(html)) reasons.push('a 555 phone number');
  return reasons;
}

export function deadDestinations(parsed, html) {
  const hits = [];
  for (const l of parsed?.links || []) {
    const href = (l.href ?? '').trim();
    if (href === '' || href === '#') hits.push(`link "${String(l.text || 'untitled').replace(/\s+/g, ' ').slice(0, 80)}" has href="${href}"`);
  }
  for (const m of String(html || '').matchAll(/<form\b([^>]*)>/gi)) {
    const tag = m[1] || '';
    const action = /\baction\s*=\s*(?:"([^"]*)"|'([^']*)'|([^\s>]+))/i.exec(tag);
    if (!action) {
      hits.push('a form has no action');
      continue;
    }
    const value = (action[1] ?? action[2] ?? action[3] ?? '').trim();
    if (value === '' || value === '#') hits.push(`a form action is "${value}"`);
  }
  return hits;
}

const SECRET_PATTERNS = [
  ['AWS access key', /AKIA[0-9A-Z]{16}/],
  ['private key', /-----BEGIN (?:RSA |OPENSSH |EC |DSA )?PRIVATE KEY-----/],
  ['Stripe live secret', /sk_live_[0-9a-zA-Z]{10,}/],
  ['Stripe restricted key', /rk_live_[0-9a-zA-Z]{10,}/],
  ['GitHub token', /ghp_[A-Za-z0-9]{20,}/],
  ['GitHub fine-grained token', /github_pat_[A-Za-z0-9_]{20,}/],
  ['Slack token', /xox[baprs]-[A-Za-z0-9-]{10,}/],
  ['Google API key', /AIza[0-9A-Za-z\-_]{35}/],
  ['SendGrid API key', /SG\.[A-Za-z0-9_\-]{16,}\.[A-Za-z0-9_\-]{16,}/],
  ['Slack webhook', /hooks\.slack\.com\/services\/T[A-Z0-9]{6,}\/B[A-Z0-9]{6,}\/[A-Za-z0-9]{10,}/],
  ['assigned secret', /(?:api[_-]?key|api[_-]?secret|secret[_-]?key|aws_secret_access_key|private[_-]?token)\s*[:=]\s*['"][A-Za-z0-9_\-+/=]{12,}['"]/i],
];

export function secretHits(text) {
  const hits = [];
  for (const [name, re] of SECRET_PATTERNS) if (re.test(text)) hits.push(name);
  return hits;
}

